// Copies the extension's prompts, schemas and Claude calls (ai/claude-service.js)
// into lib/ so the deployed backend (root directory: backend/) behaves exactly
// like the extension. Runs automatically before every build.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.join(here, '../../ai/claude-service.js');
const target = path.join(here, '../lib/claude-service.js');
const HEADER = '// GENERATED by scripts/sync-service.mjs from ../ai/claude-service.js. Edit that file, then run `npm run sync`.\n';

let text;
try {
    text = readFileSync(source, 'utf8');
} catch (e) {
    // Deploying from backend/ alone: keep the committed copy.
    console.log('ai/claude-service.js not found; keeping lib/claude-service.js as committed.');
    process.exit(0);
}
writeFileSync(target, HEADER + text);
console.log('lib/claude-service.js updated');
